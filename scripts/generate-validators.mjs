import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'src/domain/generated-validators.js');
const schemaNames = [
  'species',
  'catalog',
  'document',
  'task-data',
  'local-file',
  'reactcode-message',
];

const schemas = Object.fromEntries(
  await Promise.all(
    schemaNames.map(async (name) => [
      name,
      JSON.parse(await readFile(path.join(root, `schemas/${name}.schema.json`), 'utf8')),
    ]),
  ),
);

const ajv = new Ajv2020({
  allErrors: true,
  strict: true,
  code: { esm: true, source: true },
});
addFormats(ajv);
for (const schema of Object.values(schemas)) ajv.addSchema(schema);

const exports = {
  validateSpecies: schemas.species.$id,
  validateCatalog: schemas.catalog.$id,
  validateDocument: schemas.document.$id,
  validateTaskData: schemas['task-data'].$id,
  validateLocalFile: schemas['local-file'].$id,
  validateMessage: schemas['reactcode-message'].$id,
};

const generated = standaloneCode(ajv, exports)
  .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'ucs2length')
  .replaceAll(
    'require("ajv-formats/dist/formats").fullFormats["date-time"]',
    'fullFormats["date-time"]',
  )
  .replaceAll(/\/\*# sourceURL="[^"]+" \*\//gu, '');

if (generated.includes('require(')) {
  throw new Error('Standalone validator output contains an unexpected CommonJS runtime import');
}

const output = `/* eslint-disable */
// @ts-nocheck
// Generated by scripts/generate-validators.mjs. Do not edit by hand.
function ucs2length(value) {
  let length = 0;
  for (let index = 0; index < value.length; index += 1) {
    const code = value.charCodeAt(index);
    if (code >= 0xd800 && code <= 0xdbff && index + 1 < value.length) {
      const next = value.charCodeAt(index + 1);
      if (next >= 0xdc00 && next <= 0xdfff) index += 1;
    }
    length += 1;
  }
  return length;
}
const fullFormats = {
  'date-time': {
    validate(value) {
      const match = /^(\\d{4})-(\\d{2})-(\\d{2})[Tt ](?:[01]\\d|2[0-3]):[0-5]\\d:[0-5]\\d(?:\\.\\d+)?(?:[Zz]|[+-](?:[01]\\d|2[0-3]):[0-5]\\d)$/u.exec(value);
      if (!match) return false;
      const year = Number(match[1]);
      const month = Number(match[2]);
      const day = Number(match[3]);
      if (month < 1 || month > 12 || day < 1) return false;
      return day <= new Date(Date.UTC(year, month, 0)).getUTCDate();
    },
  },
};
${generated}
`;

if (process.argv.includes('--check')) {
  const existing = await readFile(outputPath, 'utf8').catch(() => '');
  if (existing !== output) {
    throw new Error('Generated validators are stale; run npm run generate:validators');
  }
} else {
  await writeFile(outputPath, output, 'utf8');
  console.log(`Generated ${path.relative(root, outputPath)}`);
}
